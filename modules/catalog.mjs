export function buildDefaultLicenseForSpoke(
  siteKey,
  siteName = "",
  domain = "",
  brandingOverrides = {}
) {
  const isSonitorIsolated = String(siteKey || "").toLowerCase().includes("sonitor") || String(domain || "").toLowerCase().includes("sonitor");
  if (DEFAULT_TENANT_LICENSES[siteKey]) {
    const base = structuredClone(DEFAULT_TENANT_LICENSES[siteKey]);
    const merged = {
      ...base,
      ...(brandingOverrides || {}),
    };
    if (!Array.isArray(merged.enabledModules)) merged.enabledModules = Array.isArray(base.enabledModules) ? [...base.enabledModules] : [];
    const hiddenSet = new Set(Array.isArray(merged.hiddenModules) ? merged.hiddenModules : []);
    const disabledSet = new Set(Array.isArray(merged.disabledModules) ? merged.disabledModules : []);
    merged.disabledModules = Array.from(disabledSet);
    merged.hiddenModules = Array.from(hiddenSet);
    if (!isSonitorIsolated) {
      for (const code of UNIVERSAL_MOD_LIBRARY_CODES) {
        if (!hiddenSet.has(code) && !disabledSet.has(code) && !merged.enabledModules.includes(code)) {
          merged.enabledModules.push(code);
        }
      }
    }
    merged.enabledModules = merged.enabledModules.filter(c => !disabledSet.has(c) && !hiddenSet.has(c));
    return merged;
  }
  const defaultMods = GREENTREE_MODULE_CATALOG.filter((m) => m.defaultEnabled).map((m) => m.code);
  const overrideMods = Array.isArray(brandingOverrides?.enabledModules) ? [...brandingOverrides.enabledModules] : null;
  const combinedMods = overrideMods !== null ? [...overrideMods] : [...defaultMods];
  const hiddenSet = new Set(Array.isArray(brandingOverrides?.hiddenModules) ? brandingOverrides.hiddenModules : []);
  const disabledSet = new Set(Array.isArray(brandingOverrides?.disabledModules) ? brandingOverrides.disabledModules : []);
  if (!isSonitorIsolated) {
    for (const code of UNIVERSAL_MOD_LIBRARY_CODES) {
      if (!hiddenSet.has(code) && !disabledSet.has(code) && !combinedMods.includes(code)) {
        combinedMods.push(code);
      }
    }
  }
  const finalEnabledMods = Array.from(new Set(combinedMods)).filter(c => !disabledSet.has(c) && !hiddenSet.has(c));
  return {
    siteKey,
    siteName: siteName || siteKey,
    portalTitle: brandingOverrides.portalTitle || `${siteName || siteKey} Portal`,
    logoUrl: brandingOverrides.logoUrl || "",
    domain: domain || `${siteKey}.com`,
    vertical: brandingOverrides.vertical || "Commercial Enterprise",
    brandColor: brandingOverrides.brandColor || "#2563eb",
    sidebarBg: brandingOverrides.sidebarBg || "#1b1b1f",
    topbarBg: brandingOverrides.topbarBg || "#0f172a",
    planTier: brandingOverrides.planTier || "growth_retainer",
    monthlyRate: brandingOverrides.monthlyRate ?? 299,
    billingStatus: brandingOverrides.billingStatus || "active",
    primaryGateway: brandingOverrides.primaryGateway || "whmcs",
    gateways: brandingOverrides.gateways || {
      whmcsUrl: "https://customers.greentreehosting.com/clientarea.php",
      stripeUrl: "",
      squareUrl: "",
      paypalUrl: "",
      authnetUrl: "",
    },
    ...(brandingOverrides || {}),
    enabledModules: finalEnabledMods,
    hiddenModules: Array.from(hiddenSet),
    disabledModules: Array.from(disabledSet),
  };
}

